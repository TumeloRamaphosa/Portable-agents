#!/usr/bin/env python3
"""Dark Factory local bridge — 127.0.0.1 only. Mock / demo mode."""
from __future__ import annotations
import json, os, re, datetime
from http.server import ThreadingHTTPServer, SimpleHTTPRequestHandler
from pathlib import Path

ROOT = Path(__file__).resolve().parent
INTAKE = Path(os.environ.get("VOICE_INTAKE_DIR", "/root/voice-intake"))
PRDS = INTAKE / "prds"
LEADS = INTAKE / "leads"
PRDS.mkdir(parents=True, exist_ok=True)
LEADS.mkdir(parents=True, exist_ok=True)
HOST, PORT = "127.0.0.1", 8787

def slugify(s: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9]+", "-", (s or "untitled").strip().lower()).strip("-")
    return (s or "untitled")[:60]

def write_prd(payload: dict) -> dict:
    title = payload.get("title") or payload.get("problem") or "product-intake"
    date = datetime.datetime.now().strftime("%Y-%m-%d")
    path = PRDS / f"{date}-{slugify(title)}.md"
    body = f"""# Product Requirements — {title}

> Generated by Dark Factory intake agent (demo / mock). Not a live client record.

## Problem
{payload.get('problem', '')}

## Users
{payload.get('users', '')}

## Must-have features
{payload.get('must_haves', '')}

## Constraints
{payload.get('constraints', '')}

## Success criteria
{payload.get('success', '')}

## Deadline
{payload.get('deadline', '')}

## Budget / Approver
{payload.get('budget_approver', '')}

## Transcript notes
{payload.get('notes', '')}

---
Saved: {datetime.datetime.now().isoformat(timespec='seconds')}
Path: {path}
"""
    path.write_text(body, encoding="utf-8")
    return {"ok": True, "path": str(path), "markdown": body}

def write_lead(payload: dict) -> dict:
    name = payload.get("name") or "lead"
    date = datetime.datetime.now().strftime("%Y-%m-%d")
    path = LEADS / f"{date}-{slugify(name)}.md"
    body = f"""# Lead summary — {name}

> Generated by Dark Factory sales agent (demo / mock). Placeholder product facts only.

## Contact
- Name: {payload.get('name', '')}
- Company: {payload.get('company', '')}
- Consent to follow up: {payload.get('consent', '')}

## Need
{payload.get('need', '')}

## Budget (stated, not quoted)
{payload.get('budget', 'Not discussed / to be confirmed by team')}

## Timeline
{payload.get('timeline', '')}

## Product interest (PLACEHOLDER facts)
{payload.get('product_interest', '')}

## Disclosures made
- Identified as AI assistant
- No prices, discounts, payments or commitments agreed
- Draft pricing must be confirmed by the Studex team
- Opt-out honoured if requested

## Notes
{payload.get('notes', '')}

---
Saved: {datetime.datetime.now().isoformat(timespec='seconds')}
Path: {path}
"""
    path.write_text(body, encoding="utf-8")
    return {"ok": True, "path": str(path), "markdown": body}

class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *a, **k):
        super().__init__(*a, directory=str(ROOT), **k)

    def _json(self, code: int, obj):
        data = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self):
        if self.path.startswith("/api/health"):
            return self._json(200, {"ok": True, "mode": "demo", "host": HOST, "port": PORT, "knowledge": str((ROOT / "agent-knowledge.md").exists())})
        if self.path.startswith("/api/knowledge"):
            kp = ROOT / "agent-knowledge.md"
            if not kp.exists():
                return self._json(404, {"error": "knowledge missing"})
            text = kp.read_text(encoding="utf-8")
            return self._json(200, {
                "bytes": len(text),
                "markdown": text,
                "rules": [
                    "You are AI.",
                    "Never quote draft/unapproved prices (including StudBot Rise and Dark Factory tiers).",
                    "Founder about section is not for public speech until approved.",
                    "Excluded partners are out of scope.",
                    "Prefer: I'll take that for the team to confirm.",
                ],
            })
        if self.path.startswith("/api/files"):
            files = {
                "prds": [str(p) for p in sorted(PRDS.glob("*.md"))][-10:],
                "leads": [str(p) for p in sorted(LEADS.glob("*.md"))][-10:],
            }
            return self._json(200, files)
        if self.path.startswith("/api/read?"):
            from urllib.parse import urlparse, parse_qs
            qs = parse_qs(urlparse(self.path).query)
            p = (qs.get("path") or [""])[0]
            allowed = list(PRDS.glob("*.md")) + list(LEADS.glob("*.md"))
            match = next((x for x in allowed if str(x) == p), None)
            if not match:
                return self._json(404, {"error": "not found"})
            return self._json(200, {"path": str(match), "markdown": match.read_text(encoding="utf-8")})
        return super().do_GET()

    def do_POST(self):
        length = int(self.headers.get("Content-Length") or 0)
        raw = self.rfile.read(length) if length else b"{}"
        try:
            payload = json.loads(raw.decode() or "{}")
        except Exception:
            return self._json(400, {"error": "bad json"})
        if self.path == "/api/prd":
            return self._json(200, write_prd(payload))
        if self.path == "/api/lead":
            return self._json(200, write_lead(payload))
        if self.path == "/api/mock-call":
            # Local mock only — no carrier, no OpenClaw required for demo page
            return self._json(200, {
                "ok": True,
                "provider": "mock",
                "callId": "mock-" + datetime.datetime.now().strftime("%H%M%S"),
                "to": payload.get("to") or "+15550005678",
                "from": "+15550001234",
                "status": "completed-sim",
                "note": "Simulated mock call. No network. Placeholder numbers only.",
            })
        return self._json(404, {"error": "unknown"})

    def log_message(self, fmt, *args):
        print("[dark-factory]", fmt % args)

if __name__ == "__main__":
    httpd = ThreadingHTTPServer((HOST, PORT), Handler)
    print(f"Dark Factory listening on http://{HOST}:{PORT}/ (demo mode)")
    httpd.serve_forever()
